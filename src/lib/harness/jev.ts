import type { DecisionData, DecisionEvent, DecisionQuestion, DecisionQuestionType, TargetId } from "./types";

export const JEV_ENDPOINT = "https://api.typesafe.ai/v1/systemone";
export const JEV_KEY_ENV = "TYPESAFE_API_KEY";

export type JevAnswer =
  | { type: "noul"; noul: number }
  | { type: "choice"; choice: string }
  | { type: "score"; score: number };

const QUESTION_KEY = /^[A-Za-z][A-Za-z0-9_-]*$/;

export function questionKey(name: string, fallback: string): string {
  const trimmed = name.trim();
  return QUESTION_KEY.test(trimmed) ? trimmed : fallback;
}

/** Choice lines are `key: meaning`. A line with no colon is a key and nothing else. */
export function choiceCriteria(lines: string[]): Record<string, string | null> {
  const criteria: Record<string, string | null> = {};
  for (const line of lines) {
    const split = line.indexOf(":");
    const key = (split === -1 ? line : line.slice(0, split)).trim();
    if (!key) continue;
    const meaning = split === -1 ? "" : line.slice(split + 1).trim();
    criteria[key] = meaning || null;
  }
  return criteria;
}

export function jevQuestions(questions: DecisionQuestion[]): Record<string, unknown> {
  const body: Record<string, unknown> = {};
  questions.forEach((question, index) => {
    const key = questionKey(question.name, `question${index + 1}`);
    const instructions = question.instructions.trim();
    if (question.type === "choice") {
      body[key] = { type: "choice", instructions, criteria: choiceCriteria(question.criteria) };
    } else if (question.type === "score") {
      body[key] = { type: "score", instructions, criteria: question.criteria.map((level) => level.trim()).filter(Boolean) };
    } else {
      body[key] = { type: "noul", instructions };
    }
  });
  return body;
}

export function answerBlocks(question: DecisionQuestion, answer: JevAnswer): boolean {
  if (question.type === "noul" && answer.type === "noul") return answer.noul >= question.blockAt;
  if (question.type === "choice" && answer.type === "choice") return question.blockChoices.includes(answer.choice);
  if (question.type === "score" && answer.type === "score") return answer.score >= question.blockAt;
  return false;
}

/** JSON a hook prints when Jev says to stop the action. Shape depends on the tool. */
export function blockPayload(target: TargetId, event: DecisionEvent, reason: string): Record<string, unknown> {
  if (target === "cursor") {
    if (event === "userPromptSubmit") return { continue: false, user_message: reason };
    if (event === "stop") return { followup_message: reason };
    return { permission: "deny", user_message: reason, agent_message: reason };
  }
  if (event === "preToolUse") {
    return {
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: reason,
      },
    };
  }
  return { decision: "block", reason };
}

export interface DecisionGate {
  key: string;
  type: DecisionQuestionType;
  blockChoices: string[];
  blockAt: number;
}

export function decisionGates(questions: DecisionQuestion[]): DecisionGate[] {
  return questions.map((question, index) => ({
    key: questionKey(question.name, `question${index + 1}`),
    type: question.type,
    blockChoices: question.blockChoices,
    blockAt: question.blockAt,
  }));
}

/** A Node script the exported hook runs. It reads stdin as Jev's state. */
export function renderDecisionScript(decision: DecisionData, target: TargetId): string {
  const request = {
    model: decision.model.trim() || "jev-latest",
    questions: jevQuestions(decision.questions),
  };
  return `#!/usr/bin/env node
// Generated by Harness Studio. Asks Jev about this hook's input and blocks when a question says so.
// The API key is read from ${JEV_KEY_ENV}. It is not stored in this file.

const TARGET = ${JSON.stringify(target)};
const EVENT = ${JSON.stringify(decision.event)};
const REQUEST = ${JSON.stringify(request)};
const GATES = ${JSON.stringify(decisionGates(decision.questions))};
const ENDPOINT = ${JSON.stringify(JEV_ENDPOINT)};

const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
const state = Buffer.concat(chunks).toString("utf8");

function block(reason) {
  let out;
  if (TARGET === "cursor") {
    if (EVENT === "userPromptSubmit") out = { continue: false, user_message: reason };
    else if (EVENT === "stop") out = { followup_message: reason };
    else out = { permission: "deny", user_message: reason, agent_message: reason };
  } else if (EVENT === "preToolUse") {
    out = {
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: reason,
      },
    };
  } else {
    out = { decision: "block", reason };
  }
  process.stdout.write(JSON.stringify(out) + "\\n");
}

function reasons(answers) {
  const found = [];
  for (const gate of GATES) {
    const answer = answers?.[gate.key];
    if (!answer) continue;
    if (gate.type === "noul" && typeof answer.noul === "number" && answer.noul >= gate.blockAt) {
      found.push(gate.key + " is " + Math.round(answer.noul * 100) + "% yes");
    } else if (gate.type === "choice" && gate.blockChoices.includes(answer.choice)) {
      found.push(gate.key + " is " + answer.choice);
    } else if (gate.type === "score" && typeof answer.score === "number" && answer.score >= gate.blockAt) {
      found.push(gate.key + " scored " + answer.score);
    }
  }
  return found;
}

const key = process.env.${JEV_KEY_ENV};
if (!key) {
  block("${JEV_KEY_ENV} is not set, so this decision blocks.");
  process.exit(0);
}

let payload;
try {
  const response = await fetch(ENDPOINT, {
    method: "POST",
    headers: { Authorization: "Bearer " + key, "Content-Type": "application/json" },
    body: JSON.stringify({ ...REQUEST, state }),
    signal: AbortSignal.timeout(8000),
  });
  payload = await response.json();
  if (!response.ok) {
    block("Jev returned " + response.status + ".");
    process.exit(0);
  }
} catch {
  block("Jev could not be reached, so this decision blocks.");
  process.exit(0);
}

const found = reasons(payload.answers);
if (found.length) block(found.join("; "));
`;
}
